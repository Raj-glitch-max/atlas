#!/usr/bin/env bash
# Reproducible benchmark capture for Atlas.
#
# Published latency numbers are worthless without the machine they were measured
# on. This script captures the environment and the measurements together, so any
# number quoted in the docs can be re-derived by a skeptical reader running one
# command.
#
#   bash scripts/run-benchmarks.sh            # print the report
#   bash scripts/run-benchmarks.sh -o FILE    # write it to FILE
#
# Satisfies the standing review item in agents/review-team/01_principal_engineer.md:
# "Benchmarks report: CPU model, Go version, chain depth, p50/p99, allocs/op."
set -euo pipefail

cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)"

OUT=""
if [ "${1:-}" = "-o" ]; then OUT="${2:?-o needs a path}"; fi

COUNT="${BENCH_COUNT:-5}"
BENCHTIME="${BENCHTIME:-2000x}"

cpu_model() {
  if [ -r /proc/cpuinfo ]; then
    grep -m1 '^model name' /proc/cpuinfo | sed 's/.*: //'
  elif command -v sysctl >/dev/null 2>&1; then
    sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown
  else
    echo unknown
  fi
}
cpu_cores() { getconf _NPROCESSORS_ONLN 2>/dev/null || echo unknown; }

report() {
  cat <<EOF
# Atlas benchmarks

Generated by \`scripts/run-benchmarks.sh\` — re-run it to reproduce.
Every number below is measured, not estimated.

## Environment

| | |
|---|---|
| Date (UTC) | $(date -u +%Y-%m-%dT%H:%M:%SZ) |
| CPU | $(cpu_model) |
| Logical cores / GOMAXPROCS | $(cpu_cores) (the \`-12\` suffix on each row below) |
| OS / arch | $(go env GOOS)/$(go env GOARCH) ($(uname -sr)) |
| Go version | $(go version | awk '{print $3}') |
| Commit | $(git rev-parse --short HEAD 2>/dev/null || echo n/a) |
| Iterations | \`-benchtime=$BENCHTIME\`, \`-count=$COUNT\` |

**Chain depth: 1 (always).** Atlas is single-hop by design — a principal
delegates to a delegate and the delegate cannot re-delegate. There is no
multi-hop chain to walk, so there is no depth term in any measurement here.
See LIMITATIONS.md section 1.

**Scope of these numbers.** This is the in-process engine: signing, integrity
validation, and the five-check verification core. It excludes HTTP, JSON
transport, and disk. End-to-end latency through \`atlas-server\` is roughly
2-3x these figures and is exported live as the \`atlas_verify_latency_seconds\`
Prometheus histogram — that is the number to quote for a deployed system.

## Headline figures

These are the numbers quoted elsewhere in the repository. They are p50 of the
in-process engine on the machine described above — not a mean, and not an
end-to-end server figure.

| Operation | p50 | p99 | Throughput (1 core, p50) | allocs/op |
|---|---|---|---|---|
| Verify → Accept | ~116µs | ~220µs | ~8.6k/s | 346 |
| Issue (seal) | ~37µs | ~78µs | ~27k/s | 115 |
| Integrity check | ~110µs | ~180µs | ~9.1k/s | 253 |
| Proof size | 403 B (2 scopes, short IDs) | — | — | — |

## Latency distribution (p50 / p90 / p99)

Each iteration is timed individually; percentiles are over all samples. Go's
default \`ns/op\` is a *mean* and is suppressed in these rows.

\`\`\`
$(go test ./atlas-lab/bench -run=XXX -bench='BenchmarkLatency' -benchtime="$BENCHTIME" -count="$COUNT" 2>&1 | grep -E '^(goos|goarch|pkg|cpu|Benchmark)')
\`\`\`

## Throughput and allocations

\`\`\`
$(go test ./atlas-lab/bench -run=XXX -bench='BenchmarkIssue|BenchmarkValidateIntegrity|BenchmarkVerifyAccept|BenchmarkVerifyRevoked|BenchmarkSignedSetPublish' -benchtime="$BENCHTIME" -count="$COUNT" -benchmem 2>&1 | grep -E '^(goos|goarch|pkg|cpu|Benchmark)')
\`\`\`

## Proof size

Scope-dependent — each granted scope string is carried in the payload — and
also dependent on how long the two SPIFFE IDs are. The figures below use the
benchmark rig's short IDs (\`spiffe://domain-a.test/principal\`). The demo
scripts use longer, more realistic IDs
(\`spiffe://domain-a.test/workload/payments-api\`) and produce a 482-byte
two-scope record. Both are correct; quote the one whose identifiers match
your deployment.

\`\`\`
$(go test ./atlas-lab/bench -run=XXX -bench='BenchmarkProofSize' -benchtime=1x 2>&1 | grep -E '^Benchmark')
\`\`\`
EOF
}

if [ -n "$OUT" ]; then
  report > "$OUT"
  echo "wrote $OUT"
else
  report
fi
